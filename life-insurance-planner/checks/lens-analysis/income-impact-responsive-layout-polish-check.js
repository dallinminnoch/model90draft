#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const { execSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..", "..");

function readRepoFile(relativePath) {
  return fs.readFileSync(path.join(repoRoot, relativePath), "utf8");
}

function getRule(source, selector) {
  const escapedSelector = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = source.match(new RegExp(`(?:^|\\n)\\s*${escapedSelector}\\s*\\{([\\s\\S]*?)\\}`, "m"));
  assert.ok(match, `Expected CSS rule for ${selector}.`);
  return match[1];
}

function getRuleContaining(source, selector, requiredPattern) {
  const escapedSelector = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const matches = Array.from(source.matchAll(new RegExp(`(?:^|\\n)\\s*${escapedSelector}\\s*\\{([\\s\\S]*?)\\}`, "gm")));
  const match = matches.find((candidate) => requiredPattern.test(candidate[1]));
  assert.ok(match, `Expected CSS rule for ${selector} containing ${requiredPattern}.`);
  return match[1];
}

function assertRuleDeclaration(rule, pattern, message) {
  assert.match(rule, pattern, message);
}

function getChangedFiles() {
  return execSync("git diff --name-only --", {
    cwd: repoRoot,
    encoding: "utf8"
  }).split(/\r?\n/).filter(Boolean);
}

const componentsSource = readRepoFile("components.css");
const layoutSource = readRepoFile("layout.css");
const displaySource = readRepoFile("app/features/lens-analysis/income-loss-impact-display.js");

assert.match(
  displaySource,
  /function renderTopSummaryStrip\(timelineResult\)[\s\S]*income-impact-summary-strip[\s\S]*renderFinancialSecurityCard\(timelineResult\)[\s\S]*lifestyleReadout/,
  "Income Impact top row should still be the summary strip generated by the display renderer."
);

const summaryStripRule = getRule(componentsSource, ".income-impact-summary-strip");
assertRuleDeclaration(summaryStripRule, /display:\s*flex;/, "Summary strip should remain flex-based.");
assertRuleDeclaration(summaryStripRule, /flex-wrap:\s*wrap;/, "Summary strip should wrap instead of forcing page width.");
assertRuleDeclaration(summaryStripRule, /min-width:\s*0;/, "Summary strip should keep a shrink contract.");
assertRuleDeclaration(summaryStripRule, /overflow:\s*hidden;/, "Summary strip should preserve containment.");

const financialCardRule = getRule(
  componentsSource,
  ".income-impact-summary-strip > [data-income-impact-financial-security-card]"
);
assertRuleDeclaration(financialCardRule, /flex:\s*1\s+1\s+28rem;/, "Financial security card should be allowed to shrink and wrap.");
assertRuleDeclaration(financialCardRule, /max-width:\s*100%;/, "Financial security card should not exceed the content column.");
assertRuleDeclaration(financialCardRule, /min-width:\s*min\(100%,\s*24rem\);/, "Financial security card should have a bounded minimum width.");

const explanationRule = getRule(
  componentsSource,
  ".income-impact-summary-strip > [data-income-impact-financial-security-card] p"
);
assertRuleDeclaration(explanationRule, /overflow:\s*hidden;/, "Financial security explanation should not force row width.");
assertRuleDeclaration(explanationRule, /text-overflow:\s*ellipsis;/, "Financial security explanation should ellipsize when constrained.");

const lifestyleRule = getRule(componentsSource, ".income-impact-lifestyle-impact-readout");
assertRuleDeclaration(lifestyleRule, /display:\s*flex;/, "Lifestyle impact readout should remain flex-based.");
assertRuleDeclaration(lifestyleRule, /flex-wrap:\s*wrap;/, "Lifestyle impact readout should wrap internally.");
assertRuleDeclaration(lifestyleRule, /flex:\s*1\s+1\s+24rem;/, "Lifestyle impact readout should be allowed to shrink and wrap.");
assertRuleDeclaration(lifestyleRule, /max-width:\s*100%;/, "Lifestyle impact readout should stay inside the content column.");
assertRuleDeclaration(lifestyleRule, /min-width:\s*min\(100%,\s*20rem\);/, "Lifestyle impact readout should have a bounded minimum width.");

const lifestyleStatRule = getRule(componentsSource, ".income-impact-lifestyle-impact-readout__stat");
assertRuleDeclaration(lifestyleStatRule, /min-width:\s*0;/, "Lifestyle stat cells should keep a shrink contract.");
assertRuleDeclaration(lifestyleStatRule, /max-width:\s*100%;/, "Lifestyle stat cells should not force row width.");

const lifestyleStatusRule = getRule(componentsSource, ".income-impact-lifestyle-impact-readout__status");
assertRuleDeclaration(lifestyleStatusRule, /min-width:\s*0;/, "Lifestyle primary status should be shrinkable.");
assertRuleDeclaration(lifestyleStatusRule, /max-width:\s*100%;/, "Lifestyle primary status should stay contained.");
assertRuleDeclaration(lifestyleStatusRule, /overflow:\s*hidden;/, "Lifestyle primary status should not force row width.");
assertRuleDeclaration(lifestyleStatusRule, /text-overflow:\s*ellipsis;/, "Lifestyle primary status should ellipsize when constrained.");

const graphWrapperRule = getRuleContaining(componentsSource, ".income-impact-graph", /display:\s*grid;/);
assertRuleDeclaration(graphWrapperRule, /min-width:\s*0;/, "Graph wrapper should keep a shrink contract.");
assertRuleDeclaration(graphWrapperRule, /overflow:\s*visible;/, "Graph wrapper should preserve visible event/readout behavior.");

const graphSvgRule = getRule(componentsSource, ".income-impact-graph-svg");
assertRuleDeclaration(graphSvgRule, /--income-impact-graph-aspect-ratio:\s*1000 \/ 400;/, "Graph SVG aspect ratio should stay tied to the current viewBox contract.");
assertRuleDeclaration(graphSvgRule, /--income-impact-graph-max-width:\s*100%;/, "Graph SVG should use the available chart-card width.");
assertRuleDeclaration(graphSvgRule, /width:\s*100%;/, "Graph SVG should fill the graph wrapper width.");
assertRuleDeclaration(graphSvgRule, /max-width:\s*var\(--income-impact-graph-max-width\);/, "Graph SVG max-width should be container based.");
assertRuleDeclaration(graphSvgRule, /margin-inline:\s*0;/, "Graph SVG should not remain centered inside a narrower max-width column.");
assert.doesNotMatch(
  graphSvgRule,
  /calc\(250vh - 60rem\)|clamp\(42rem/,
  "Graph SVG should not use the previous viewport-height-derived width hack."
);

const contentSectionRule = getRule(
  layoutSource,
  'body[data-step="income-impact"] .income-impact-content-stack > .income-impact-section'
);
assertRuleDeclaration(contentSectionRule, /min-width:\s*0;/, "Prior main content shrink contract should remain present.");

const changedFiles = getChangedFiles();
const allowedChangedFiles = new Set([
  "life-insurance-planner/components.css",
  "life-insurance-planner/checks/lens-analysis/income-loss-impact-visual-timeline-check.js",
  "life-insurance-planner/checks/lens-analysis/income-impact-main-content-shrink-contract-check.js",
  "life-insurance-planner/checks/lens-analysis/income-impact-responsive-layout-polish-check.js"
]);
const unexpectedChangedFiles = changedFiles.filter((file) => !allowedChangedFiles.has(file));
assert.deepEqual(unexpectedChangedFiles, [], `Unexpected files changed: ${unexpectedChangedFiles.join(", ")}`);

const forbiddenFilePatterns = [
  /income-impact-timeline-graph-model\.js/,
  /income-loss-impact-display\.js/,
  /income-impact-scenario-composer-calculations\.js/,
  /household-wealth-projection-calculations\.js/,
  /savings-resource-allocation-adapter\.js/,
  /coverage-timeline-engine\.js/,
  /coverage-timeline-existing-coverage-adapter\.js/,
  /coverage-timeline-hypothetical-policy-layer-helper\.js/,
  /tokens\.css/
];
forbiddenFilePatterns.forEach((pattern) => {
  assert.ok(!changedFiles.some((file) => pattern.test(file)), `Forbidden file changed: ${pattern}`);
});

const diff = execSync("git diff --", {
  cwd: repoRoot,
  encoding: "utf8"
});
assert.doesNotMatch(diff, /!important/, "Responsive polish pass should not add !important.");

console.log("income-impact-responsive-layout-polish-check passed");
